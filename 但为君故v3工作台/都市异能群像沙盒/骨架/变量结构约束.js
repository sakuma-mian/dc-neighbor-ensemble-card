const 玩家 = z
  .object({
    // 觉醒后固定的那个能力。一经确定不再改变（可以提升用法与规模，不会变成另一个能力）
    能力本质: z.string().prefault(''),

    // 常规成长的两个维度
    // 【第 05 阶变更】值域从 0–5 扩到 0–10（D-054），与"数值整体 ×10 膨胀"配套。
    // 单点权重 = 50 分，所以这两项各自的满分是 500，两项合计 1000。
    掌控度: 数值字段(0, 10, 1),
    承载上限: 数值字段(0, 10, 1),

    // 基础战斗力：战力系统的核心数值（第 05 阶新增，D-053 / D-055）
    // 它是**投影字段**：掌控度与承载上限是权威源，战力值由它们加总而来。
    //   = 掌控度×50 + 承载上限×50 + 异化修正 + 血统加成
    // 写者只有模型，且**只在跃迁时更新**（平时每轮不许动它）。
    // 为什么显式记一个"算得出来"的值：状态栏要直接读它、模型判定战力时要直接用它，
    // 而"让模型每轮现算"比"存一个数"更容易出错（模型不擅长算术）。
    // 上限 1300 = 掌控10(500) + 承载10(500) + 异化(200) + 血统(300)。
    基础战力: 数值字段(0, 1300, 100),

    // 代价：内在损耗（伤自己）
    内在损耗: 数值字段(0, 100, 0),

    // 代价：外在暴露（一个数值，会随时间或休整回落）
    // 决定 D-046：暴露合并为一个数值
    暴露程度: 数值字段(0, 100, 0),

    // 社会身份：不会自己回落。
    // 与"暴露程度"的区别：暴露程度是"你藏得怎么样"，身份记录是"你在档案里是什么人"。
    身份记录: 枚举字段(身份记录选项),

    // 异化路线（极少数人让能力发生质变的危险路线）
    异化状态: 枚举字段(异化状态选项),

    // 血统认知：玩家对自己出身的了解程度（高血统者觉醒前与普通人无异）
    血统认知: 枚举字段(血统认知选项),

    // 当前状态：用可变的键值对，只放"过期了就能删"的临时状态
    // 例：{ '身上有伤': '左臂', '正在被谁找': '管理局' }
    当前状态: z.record(z.string(), z.string()).prefault({}),

    // 圈内代号：别人给你起的名字。空 = 你还没有名声
    圈内代号: z.string().prefault(''),
  })
  .prefault({});

