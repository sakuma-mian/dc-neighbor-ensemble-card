// ============================================================================
// MVU Zod 变量结构约束
// 项目：都市异能群像沙盒
// 依据：B1_变量更新规则.md（v1.0.0）+ 变量表字段台账（第04阶存档 §3）
// ============================================================================
//
// 【这个文件干什么】
// 定义变量的"合法结构"。模型写出的值如果不符合这里的规定，会被自动修正或兜底，
// 而不是让坏数据静默传下去。
//
// 【三条铁律，改动前务必看】
// 1. z 是酒馆助手注入的全局变量，**绝对不要** import zod，也**不要**从网上另引一份。
//    否则跨实例的类型检查会全部失败、parse 会静默产出 NaN 或 undefined
//    ——不报错，但数据全是坏的。
// 2. registerMvuSchema 必须在 $() 回调里调用（等 DOM 就绪），不能在模块顶层直接调。
// 3. 对象字段一律用 .prefault({})，不要用 .default({})。
//    区别：prefault 的后备值会经过 transform 处理，default 会绕过它。
//
// 【一个容易踩的坑，写在这里免得后人重复踩】
// .prefault() 定义在 ZodEffects 上，调用它会返回一个 _ZodEffects 实例。
// 而 _ZodEffects 上**没有** prefault 方法——所以形式正确的写法是
//     z.string().transform(...).prefault(x)     ← 可以
//     z.number().transform(...).prefault(x).prefault(y)  ← 第二个无效，别这么写
// 第二个不会报错，只会让默认值静默失效。本文件里所有带 transform 的字段，
// prefault 都只写一次。
//
// 【层级说明】
// schema 对应 stat_data 层级，必须以 z.object(...) 开头。
// ============================================================================

// ---------------------------------------------------------------------------
// 工具箱
// ---------------------------------------------------------------------------

// 带限幅的数值字段。
// 为什么需要它：模型很容易写出 1000 这种越界值。限幅比事后修数据便宜。
function 数值字段(最小值, 最大值, 默认值) {
  return z
    .coerce.number()
    .transform(v => {
      if (!Number.isFinite(v)) return 默认值;
      return Math.min(最大值, Math.max(最小值, v));
    })
    .prefault(默认值);
}

// 枚举字段：值不在候选里就落回第一个候选。
// 这么设计是为了"不炸"——模型自己发明一个等级时，数据会回到安全值，
// 而不是让整个变量结构校验失败。
function 枚举字段(选项) {
  return z
    .string()
    .transform(v => (选项.includes(v) ? v : 选项[0]))
    .catch(选项[0])
    .prefault(选项[0]);
}

// ---------------------------------------------------------------------------
// 候选值：集中在这里，方便你以后改
// ---------------------------------------------------------------------------
// 这些对应第 1~3 阶冻结的设定条款。改动时请同步更新：
//   - 存档/第01阶-世界观与异能基调.md
//   - 存档/第04阶-首版范围与交付物.md（字段台账）
//   - 骨架/变量更新规则.txt（给模型看的那份说明）
const 身份记录选项 = ['未登记', '被登记', '被通缉'];
const 异化状态选项 = ['未涉足', '进行中', '已异化'];
const 血统认知选项 = ['未知', '存疑', '已知'];
const 位阶选项 = ['不入流', '中游', '高位', '传闻极强', '深不可测'];
const 已知程度选项 = ['未知', '有传闻', '已确认'];

// 故事线进度允许的阶段标记（可自由扩展，仅作文档用）
// 说明：这里**不做**成枚举校验。理由：故事线阶段是你会不断补充的内容，
// 做成硬枚举会让"你新增一个阶段名"变成"需要改 schema"。
const 故事线进度 = z.string().prefault('');

// ---------------------------------------------------------------------------
// 玩家层
// ---------------------------------------------------------------------------
const 玩家 = z
  .object({
    // 觉醒后固定的那个能力。一经确定不再改变（可以提升用法与规模，不会变成另一个能力）
    能力本质: z.string().prefault(''),

    // 常规成长的两个维度
    掌控度: 数值字段(0, 5, 1),
    承载上限: 数值字段(0, 5, 1),

    // 代价：内在损耗（伤自己）
    内在损耗: 数值字段(0, 100, 0),

    // 代价：外在暴露（一个数值，会随时间或休整回落）
    // 决定 D-046：暴露合并为一个数值
    暴露程度: 数值字段(0, 100, 0),

    // 社会身份：不会自己回落。
    // 与"暴露程度"的区别：暴露程度是"你藏得怎么样"，身份记录是"你在档案里是什么人"。
    身份记录: 枚举字段(身份记录选项),

    // 异化路线（极少数人让能力发生质变的危险路线）
    异化状态: 枚举字段(异化状态选项),

    // 血统认知：玩家对自己出身的了解程度（高血统者觉醒前与普通人无异）
    血统认知: 枚举字段(血统认知选项),

    // 当前状态：用可变的键值对，只放"过期了就能删"的临时状态
    // 例：{ '身上有伤': '左臂', '正在被谁找': '管理局' }
    当前状态: z.record(z.string(), z.string()).prefault({}),

    // 圈内代号：别人给你起的名字。空 = 你还没有名声
    圈内代号: z.string().prefault(''),
  })
  .prefault({});

// ---------------------------------------------------------------------------
// 单个角色的状态
// ---------------------------------------------------------------------------
// 注意：key 用真名（唯一、稳定）；圈内代号放记录内的字段，因为代号会变、会骗人。
const 单角色 = z
  .object({
    // 故事线进度：位置由它推导，不单独记"他现在在哪"（位置最容易过期）
    故事线进度,

    // 位阶三件套：这张卡的命门。缺任何一项，"实测数据会骗人"这个设定就废了
    位阶传闻: 枚举字段(位阶选项),
    位阶真实: 枚举字段(位阶选项),
    玩家已知程度: 枚举字段(已知程度选项),

    // 与玩家的账：用标签而不用数值。
    // "欠他一次"比"好感度 73"信息量大得多，模型也更不容易用错。
    与玩家的账: z.array(z.string()).prefault([]),

    // 玩家已经掌握的他哪些底牌
    被掌握的底牌: z.array(z.string()).prefault([]),

    // 圈内代号（会变、会骗人，所以不做主键）
    圈内代号: z.string().prefault(''),

    // 是否已和玩家打过交道（决定这个条目要不要参与开局匹配）
    已接触: z.boolean().prefault(false),
  })
  .prefault({});

// ---------------------------------------------------------------------------
// 世界层
// ---------------------------------------------------------------------------
const 势力状态 = z
  .object({
    管理局: z.string().prefault(''),
    家族: z.string().prefault(''),
    散人网: z.string().prefault(''),
    没落旧家: z.string().prefault(''),
  })
  .prefault({});

// 事件线保留的最大条数。
// 为什么必须设上限：这个数组会随时间无限增长，是**最容易让提示词悄悄膨胀**的地方。
const 事件线上限 = 12;

const 世界 = z
  .object({
    // 游戏内日期，所有"上次""几天前"的时间锚
    日期: z.string().prefault(''),

    // 事件线：只记结果，不记过程。超出上限时保留最近的若干条。
    事件线: z
      .array(z.string())
      .transform(数组 => (数组.length > 事件线上限 ? 数组.slice(-事件线上限) : 数组))
      .prefault([]),

    // 三足鼎立 + 那个没落旧家，各一句话
    势力状态,

    // 当前引力源：现在有谁在找玩家（对应"每个方向都有人等你"）
    当前引力源: z.array(z.string()).prefault([]),

    // 结局进度（对应连载式更新）
    结局进度: z.string().prefault(''),

    // 变量结构版本：【只有脚本能写，模型绝不写】
    // 你以后新增字段时，脚本靠它判断要不要给老存档补默认值。
    // 每改一次变量结构就把它 +1，否则老玩家的存档会缺字段而错乱。
    变量结构版本: z.string().prefault('1.0'),
  })
  .prefault({});

// ---------------------------------------------------------------------------
// 顶层结构
// ---------------------------------------------------------------------------
// .passthrough() 的作用：模型偶尔会写入这里没声明的字段。
// 不加它，那些字段会被自动剥掉（数据静默丢失）；加了它，额外字段会被保留。
// 注意：passthrough 在深层嵌套里的行为未经验证（规范列为悬案 P7），
// 所以不要把"依赖额外字段存活"当成关键机制。
const Schema = z
  .object({
    玩家,
    角色: z.record(z.string(), 单角色).prefault({}),
    世界,
  })
  .passthrough();

// ---------------------------------------------------------------------------
// 注册
// ---------------------------------------------------------------------------
// 必须在 $() 回调中调用：需要等 DOM 就绪。
$(() => {
  registerMvuSchema(Schema);
});
