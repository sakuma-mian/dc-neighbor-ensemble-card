// ============================================================================
// 正则效果验证器 · 都市异能群像沙盒
// ============================================================================
//
// 【这个文件干什么】
// 拿一条**模拟的模型回复**，把 骨架/正则脚本.mjs 里的全部正则真跑一遍，
// 打印出「玩家会看到什么」和「模型会收到什么」，并把可疑之处报出来。
//
// 【为什么需要它】
// 正则的错法有两种，静态看字段名都发现不了：
//   1. 顺序错——兜底那条跑在渲染那条前面，把对话标记全抹了；
//   2. 漏匹配——模型写歪的标签没被消费，裸着进了 showdown，
//      触发 Issue #3996 的双 <br> 爆炸，**版面直接崩**（不是难看，是崩）。
// 这个脚本就是为了在导入酒馆之前，把这两种错挡在门外。
//
// 【怎么跑】
//   node 骨架/验证正则.mjs
// 它**不产生任何文件**，只打印结果。退出码 1 表示有断言没过。
// ============================================================================

import { 正则列表 } from './正则脚本.mjs';

const 拆 = (文本) => {
  const m = /^\/(.*)\/([gimsuy]*)$/s.exec(文本);
  if (!m) throw new Error(`findRegex 不是 /…/flags 形式：${文本}`);
  return new RegExp(m[1], m[2]);
};

// 一条尽量贴近真机的模型回复：
// 有叙述、有两段对话、有变量块，还有一处"模型写歪了"的对话标记。
const 模拟回复 = [
  '雨停了有一阵，屋檐还在滴水。',
  '',
  '藤原花奈从账本上抬起眼，指节压着纸页没动。<d s="花奈">你找谁？</d>',
  '',
  '她把书脊转向你，封面上没有题字。',
  '',
  '<d s="花奈">这条街上，下午三点以后不卖生人的东西。</d>',
  '',
  // ↓ 这一处故意写歪：属性值没加引号。兜底正则应该把它清掉，而不是漏给 showdown。
  '<d s=摊主>这条巷子通不了后街。</d>',
  '',
  '<UpdateVariable>',
  '<analysis>玩家首次走近零号房，与藤原花奈建立接触。</analysis>',
  '<JSONPatch>',
  '[{"op":"add","path":"/角色/藤原花奈","value":{"故事线进度":"首次接触","位阶传闻":"高位","位阶真实":"高位","玩家已知程度":"未知","与玩家的账":[],"被掌握的底牌":[],"圈内代号":"第零天使","已接触":true}}]',
  '</JSONPatch>',
  '</UpdateVariable>',
].join('\n');

// ---------------------------------------------------------------------------
// 复刻酒馆的深度语义（源码逻辑见 A6 §5）
// ---------------------------------------------------------------------------
// 深度：0 = 最新一楼，数字越大越旧。
// `minDepth: 6` 的语义是「只对深度 ≥ 6 的楼层执行」——也就是**只裁旧楼层**。
// 所以必须跑两个场景对比，否则会误判成"连最新一楼的变量块也裁了"。
const 该执行 = (规则, 深度) => {
  if (typeof 规则.minDepth === 'number' && 规则.minDepth >= -1 && 深度 < 规则.minDepth) return false;
  if (typeof 规则.maxDepth === 'number' && 规则.maxDepth >= 0 && 深度 > 规则.maxDepth) return false;
  return true;
};

const 跑一层 = (层, 深度) => {
  let 结果 = 模拟回复;
  for (const 规则 of 层) {
    if (!该执行(规则, 深度)) continue;
    结果 = 结果.replace(拆(规则.findRegex), 规则.replaceString);
  }
  return 结果;
};

const 显示层规则 = 正则列表.filter((r) => r.markdownOnly && !r.promptOnly);
const 送模层规则 = 正则列表.filter((r) => r.promptOnly && !r.markdownOnly);

const 显示 = 跑一层(显示层规则, 0); // 玩家看最新一楼
const 送模最新楼 = 跑一层(送模层规则, 0); // 模型看最新一楼
const 送模旧楼层 = 跑一层(送模层规则, 8); // 模型看第 8 楼（旧楼层）

// ---------------------------------------------------------------------------
// 断言
// ---------------------------------------------------------------------------
const 问题 = [];

// ① 玩家看到的这一路，不许有任何裸的自定义标签残留
const 白名单 = /^<\/?(div|span|style|details|summary|br)\b/i;
const 残留 = [...显示.matchAll(/<\/?[a-zA-Z][^>]*>/g)].map((m) => m[0]).filter((t) => !白名单.test(t));
if (残留.length) {
  问题.push(`显示层还有裸标签残留（会被 showdown 当 HTMLUnknownElement，触发 #3996）：${残留.join(' / ')}`);
}

// ② 对话标记必须被消费干净
if (/<d\b/i.test(显示)) 问题.push('显示层还有没被消费的 <d> 标签');

// ③ 变量块不许出现在玩家眼前
if (显示.includes('UpdateVariable')) 问题.push('显示层还能看到 <UpdateVariable>');
if (!显示.includes('状态记录')) 问题.push('显示层没有渲染出状态记录面板');

// ④ 对话块要真的渲染出来，且说话人和内容都在
if (!显示.includes('espd')) 问题.push('显示层没有渲染出对话块');
if (!显示.includes('花奈')) 问题.push('对话块丢了说话人');
if (!显示.includes('不卖生人的东西')) 问题.push('对话块丢了对话内容');
// 写歪的那一条：标签该被抹掉，内容该留下
if (!显示.includes('这条巷子通不了后街')) 问题.push('兜底把写歪那条的**内容**也一起抹掉了（应该只抹标签）');

// ⑤ 送模层：最新一楼保留变量块（格式示范），旧楼层才裁
if (!送模最新楼.includes('<UpdateVariable>')) {
  问题.push('送模层把最新一楼的变量块也裁掉了 —— 模型会看不到自己的输出格式');
}
if (送模旧楼层.includes('<UpdateVariable>')) {
  问题.push('送模层没有裁掉旧楼层的变量块 —— minDepth 没起作用');
}

// ⑥ 占位符对模型必须隐藏
if (送模最新楼.includes('<StatusPlaceHolderImpl/>')) 问题.push('送模层还留着状态栏占位符');

// ---------------------------------------------------------------------------
// 打印
// ---------------------------------------------------------------------------
const 精简 = (s) => s.replace(/<style>[\s\S]*?<\/style>/g, '<style>…（CSS 已省略）…</style>');

console.log('══════════════════════════════════════════════════════════');
console.log('  正则效果验证 · 都市异能群像沙盒');
console.log('══════════════════════════════════════════════════════════');
console.log('\n执行顺序（同层内按数组顺序）：');
正则列表.forEach((r, i) => {
  const 层 = r.markdownOnly ? '显示层' : r.promptOnly ? '送模层' : '⚠️ 异常';
  const 深度 = typeof r.minDepth === 'number' ? ` · 深度≥${r.minDepth}` : '';
  console.log(`  ${i + 1}. [${层}${深度}] ${r.scriptName}`);
});

console.log('\n──── 玩家看到的（显示层跑完的结果）────\n');
console.log(精简(显示));

console.log('\n──── 模型收到的（送模层 · 最新一楼，结尾 6 行）────\n');
console.log(送模最新楼.split('\n').slice(-6).join('\n'));

console.log('\n──── 模型收到的（送模层 · 第 8 楼，结尾 6 行）────\n');
console.log(送模旧楼层.split('\n').slice(-6).join('\n'));

console.log('\n──── 断言 ────\n');
if (问题.length) {
  问题.forEach((p) => console.log(`  ❌ ${p}`));
  console.log(`\n共 ${问题.length} 处问题。`);
  process.exitCode = 1;
} else {
  console.log('  ✅ 没有裸标签残留（#3996 的版面爆炸风险已挡住）');
  console.log('  ✅ 对话标记全部被消费，说话人与内容都在；写歪的那条只抹标签、留下文字');
  console.log('  ✅ 变量块对玩家不可见，但完整渲染成了面板');
  console.log('  ✅ 最新一楼的变量块对模型保留（格式示范没丢），旧楼层被裁掉');
  console.log('\n全部通过。注意：这仍然只是**离线**验证 —— 真机渲染要导入酒馆才算数。');
}
